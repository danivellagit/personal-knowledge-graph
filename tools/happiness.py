#!/usr/bin/env python3
"""data/happiness/: the single source of truth for everything the Life App shows (tools/life-app/).

One JSON file per area; each is written by the agent role that owns the area (config.local.yml life_app.areas.<id>.agents,
defaults below). Edit only your own file, then run the publisher (tools/life-app/publish.sh).
  corpo.json      the health page DATA block (fitness-coach)        medico.json    MEDICO (health-advisor)
  mente.json      psychologist (null = "in arrivo")                 lavoro.json    founder-assistant (+ linkedin-coach: `linkedin`)
  finanze.json    accountant                                        relazioni.json best-friend
  crescita.json / vita.json  best-friend (null = "in arrivo")       weekly-summary.json  the Home conclusion (weekly)
  corpo-history.json, life-health-history.json  written by the Life build (never by hand)
plus generated, never hand-edited MD recaps (happiness.md + <area>.md) linked to [[_me]].
Model and field docs: tools/life-app/DATA-MODEL.md. Sample (fake) files: tools/life-app/sample-data/.

  python3 tools/happiness.py init [--force]          create data/happiness/ from fake sample data (dates around today)
  python3 tools/happiness.py validate [FILE...]      schema check
  python3 tools/happiness.py inject --source F --out F   copy of the health page with DATA/MEDICO from the JSON
  python3 tools/happiness.py import-data-block FILE  a DATA block (or a JSON file) -> corpo.json, validated
  python3 tools/happiness.py recap [--scores F]      regenerate the MD recaps from the numbers the app shows
                                                     (tools/life-app/out/scores.json, written by build.mjs)
  python3 tools/happiness.py check                   doctor: missing or stale area files

Env: HAPPINESS_CORPO / HAPPINESS_MEDICO=FILE (inject these instead of the area files).
Never prints secrets: it reads no password or token. Like the rest of data/, data/happiness/ is gitignored by default.
"""
