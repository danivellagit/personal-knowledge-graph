def weekly_errors(v):
    errs = []
    if not isinstance(v, dict):
        return ["expected an object"]
    for k in ("week", "from", "to", "generatedAt"):
        if not isinstance(v.get(k), str):
            errs.append("missing `%s`" % k)
    for k in ("conclusion", "good", "bad", "improve"):
        x = v.get(k)
        if not isinstance(x, list) or not all(isinstance(s, str) for s in x):
            errs.append("`%s` must be a list of strings" % k)
        elif len(x) > (3 if k == "conclusion" else 2):
            errs.append("`%s`: at most %d items" % (k, 3 if k == "conclusion" else 2))
    return errs


def validate_file(p):
    area = os.path.basename(p)[:-5]
    try:
        v = load(p)
    except Exception as e:
        return ["%s: not valid JSON (%s)" % (p, e)]
    if area == "weekly-summary":
        return ["%s: %s" % (os.path.relpath(p, ROOT), e) for e in weekly_errors(v)]
    if area not in SCHEMA:
        return ["%s: not an area file (expected one of %s)" % (p, ", ".join(sorted(SCHEMA)))]
    errs = []
    check(v, SCHEMA[area], area, errs)
    if area == "corpo" and not errs:
        ds = [d["date"] for d in v["days"]]
        if ds != sorted(ds) or len(set(ds)) != len(ds):
            errs.append("corpo.days: dates must be unique and oldest first")
        if v["today"] not in ds:
            errs.append("corpo.today %s is not one of the days" % v["today"])
    if area in ("corpo-history", "life-health-history") and not errs:
        ds = [r["date"] for r in v]
        if ds != sorted(ds) or len(set(ds)) != len(ds):
            errs.append("%s: one row per date, oldest first" % area)
    if area == "lavoro" and not errs:
        if v.get("priorities"):
            rk = [x["rank"] for x in v["priorities"]]
            if rk != list(range(1, len(rk) + 1)):
                errs.append("lavoro.priorities: ranks must be 1, 2, 3... in list order")
        for k, mx in (("priorities", 3), ("wins", 3), ("openLoops", 3)):
            if len(v.get(k) or []) > mx:
                errs.append("lavoro.%s: at most %d items (keep it short)" % (k, mx))
    if area in ("relazioni", "vita", "crescita", "lavoro") and not errs and v and v.get("sfere"):
        ks = [s["key"] for s in v["sfere"]]
        if len(set(ks)) != len(ks):
            errs.append("%s.sfere: duplicate key" % area)
    return ["%s: %s" % (os.path.relpath(p, ROOT), e) for e in errs]


def cmd_validate(files):
    if not files and not os.path.isdir(HD):
        die("%s does not exist yet: run `python3 tools/happiness.py init` (fake sample data) first" % os.path.relpath(HD, ROOT), 5)
    whole = not files
    files = files or sorted(os.path.join(HD, f) for f in os.listdir(HD) if f.endswith(".json"))
    errs = []
    if whole:
        errs = ["data/happiness/%s.json missing" % a for a in list(FILES) + ["corpo-history"] if not os.path.exists(path(a))]
    for p in files:
        errs += validate_file(p)
    for e in errs:
        print("happiness: " + e, file=sys.stderr)
    if not errs:
        print("happiness: %d file(s) valid" % len(files))
    return 1 if errs else 0


def cmd_init(force=False):
    args = [sys.executable, os.path.join(LIFE, "make_sample_data.py"), "--out", HD]
    if force:
        args.append("--force")
    return subprocess.run(args).returncode


def cmd_import_data_block(f):
    if f.endswith(".json"):
        v = load(f)
    else:
        v = json.loads(node("eval-block", f))
    errs = []
    check(v, SCHEMA["corpo"], "DATA", errs)
    if errs:
        die("; ".join(errs[:5]))
    with open(path("corpo"), "w", encoding="utf8") as fh:
        json.dump(v, fh, ensure_ascii=False, indent=1)
        fh.write("\n")
    print("happiness: corpo.json <- %s (%s)" % (f, v.get("updatedAt")))
    return 0


WEIGH_INS = os.path.join(ROOT, "data", "body", "weigh-ins.md")


def weigh_ins():
    """Optional data/body/weigh-ins.md rows `| YYYY-MM-DD | time | kg | morning|legacy|other |` -> WEIGHTS of the page."""
    try:
        txt = open(WEIGH_INS, encoding="utf8").read()
    except OSError:
        return []
    rows = []
    for m in re.finditer(r"^\|\s*(\d{4}-\d\d-\d\d)\s*\|[^|]*\|\s*(\d+(?:[.,]\d+)?)\s*\|\s*(morning|legacy)\s*\|", txt, re.M):
        rows.append({"date": m.group(1), "kg": float(m.group(2).replace(",", "."))})
    return sorted(rows, key=lambda r: r["date"])


def cmd_inject(source, out):
    if not source or not os.path.isfile(source):
        die("no health page source %r" % source, 3)
    corpo = os.environ.get("HAPPINESS_CORPO") or path("corpo")
    medico = os.environ.get("HAPPINESS_MEDICO") or path("medico")
    for p in (corpo, medico):
        if not os.path.exists(p):
            die("%s missing: run `python3 tools/happiness.py init` first" % p, 4)
        errs = validate_file(p) if os.path.basename(p) in ("corpo.json", "medico.json") else []
        if errs:
            die("; ".join(errs[:5]), 4)
    args = ["inject", source, corpo, medico, out]
    ws = weigh_ins()
    if ws:
        wf = out + ".weights.json"
        with open(wf, "w") as fh:
            json.dump(ws, fh)
        args.append(wf)
    node(*args)
    print("happiness: %s = health page + data/happiness corpo/medico" % os.path.relpath(out, ROOT) if out.startswith(ROOT) else out)
    return 0


# ------------------------------------------------------------------ recap (generated MD, linked to the owner node)
def esc(s):
    return ("" if s is None else str(s)).replace("|", "\\|").replace("\n", " ")


def sc(v):
    return "in arrivo" if v is None else str(v)


def cmd_recap(scores=None):
    sp = scores or os.path.join(LIFE, "out", "scores.json")
    if not os.path.exists(sp):
        die("%s missing: run `node tools/life-app/build.mjs --scores-only` (or the publisher) first" % sp, 6)
    R = load(sp)
    stamp = dt.datetime.now().strftime("%Y-%m-%dT%H:%M")
    head = lambda title: ["---", "type: recap", "updated: %s" % R.get("todayISO"), "---", GEN_MARK + " on %s from %s; never edit by hand -->" % (stamp, os.path.relpath(sp, ROOT)), "", "# " + title, "", "Owner: [[_me]].", ""]
    L = head("Life Health")
    L += ["- Life Health (Home): %s, over %s closed day(s); today %s" % (sc(R.get("happiness")), R.get("lifeHealthDays"), sc(R.get("happinessToday"))), ""]
    L += ["| Area | Score | Agents | Tip |", "| --- | --- | --- | --- |"]
    for a in R.get("areas", []):
        L.append("| %s | %s | %s | %s |" % (esc(a["name"]), sc(a["score"]), esc(a.get("agents")), esc(a.get("tip"))))
    files = {"happiness.md": L}
    for a in R.get("areas", []):
        M = head(a["name"])
        M += ["- Score: %s" % sc(a["score"]), "- Agents: %s" % esc(a.get("agents")), "- Tip: %s" % esc(a.get("tip")), ""]
        if a.get("subs"):
            M += ["| Section | Score | Line |", "| --- | --- | --- |"] + ["| %s | %s | %s |" % (esc(s["name"]), sc(s["score"]), esc(s["line"])) for s in a["subs"]]
        files[a["id"] + ".md"] = M
    os.makedirs(HD, exist_ok=True)
    for f, lines in files.items():
        with open(os.path.join(HD, f), "w", encoding="utf8") as fh:
            fh.write("\n".join(lines) + "\n")
    print("happiness: %d recap(s) written to data/happiness/" % len(files))
    return 0


def cmd_check():
    probs = []
    now = dt.datetime.now()
    for area, f in FILES.items():
        p = path(area)
        if not os.path.exists(p):
            probs.append("%s.json missing (owner: %s)" % (area, f["agent"]))
            continue
        try:
            v = load(p)
        except Exception as e:
            probs.append("%s.json unreadable (%s)" % (area, e))
            continue
        if v is None:
            continue
        d = str(v.get(f["date"]) or "")
        try:
            t = dt.datetime.fromisoformat(d if "T" in d else d + "T00:00")
            if (now - t).total_seconds() / 3600 > f["stale_h"]:
                probs.append("%s.json is stale (%s, owner: %s)" % (area, d, f["agent"]))
        except ValueError:
            probs.append("%s.json has no valid `%s`" % (area, f["date"]))
    for x in probs:
        print("happiness: " + x)
    if not probs:
        print("happiness: all area files present and fresh")
    return 1 if probs else 0


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd, rest = argv[0], argv[1:]

    def opt(name, default=None):
        return rest[rest.index(name) + 1] if name in rest and rest.index(name) + 1 < len(rest) else default
    if cmd == "validate":
        return cmd_validate([x for x in rest if not x.startswith("-")])
    if cmd == "init":
        return cmd_init("--force" in rest)
    if cmd == "inject":
        return cmd_inject(opt("--source"), opt("--out"))
    if cmd == "import-data-block":
        return cmd_import_data_block(rest[0])
    if cmd == "recap":
        return cmd_recap(opt("--scores"))
    if cmd == "check":
        return cmd_check()
    die("unknown command %s (see --help)" % cmd)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
