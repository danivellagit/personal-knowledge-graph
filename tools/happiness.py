STATUS = {"bene", "da seguire", "critico"}
RX = {"date": re.compile(r"^\d{4}-\d\d-\d\d$"), "datetime": re.compile(r"^\d{4}-\d\d-\d\dT\d\d:\d\d(:\d\d)?$")}


def N(spec):
    return ("null", spec)


def E(*vals):
    return ("enum", set(vals))


def check(v, spec, where, errs):
    if isinstance(spec, tuple) and spec[0] == "null":
        if v is None:
            return
        spec = spec[1]
    if spec == "any":
        return
    if isinstance(spec, tuple) and spec[0] == "enum":
        if v not in spec[1]:
            errs.append("%s: %r not one of %s" % (where, v, sorted(spec[1])))
        return
    if spec in ("str", "date", "datetime"):
        if not isinstance(v, str):
            errs.append("%s: expected a string, got %s" % (where, type(v).__name__))
        elif spec in RX and not RX[spec].match(v):
            errs.append("%s: %r is not %s" % (where, v, "YYYY-MM-DD" if spec == "date" else "YYYY-MM-DDTHH:MM"))
        return
    if spec in ("num", "int"):
        if isinstance(v, bool) or not isinstance(v, (int, float)) or (spec == "int" and not isinstance(v, int)):
            errs.append("%s: expected a %s, got %r" % (where, "whole number" if spec == "int" else "number", v))
        return
    if spec == "bool":
        if not isinstance(v, bool):
            errs.append("%s: expected true/false, got %r" % (where, v))
        return
    if isinstance(spec, list):
        if not isinstance(v, list):
            errs.append("%s: expected a list" % where)
            return
        for i, x in enumerate(v):
            check(x, spec[0], "%s[%d]" % (where, i), errs)
        return
    if isinstance(spec, dict):
        if not isinstance(v, dict):
            errs.append("%s: expected an object, got %s" % (where, "null" if v is None else type(v).__name__))
            return
        extra = spec.get("*", False)
        keys = {}
        for k, s in spec.items():
            if k == "*":
                continue
            opt = k.endswith("?")
            keys[k.rstrip("?")] = (s, opt)
        for k, (s, opt) in keys.items():
            if k not in v:
                if not opt:
                    errs.append("%s: missing `%s`" % (where, k))
                continue
            check(v[k], s, "%s.%s" % (where, k), errs)
        if not extra:
            for k in v:
                if k not in keys:
                    errs.append("%s: unknown field `%s`" % (where, k))
        return
    raise ValueError("bad spec %r" % (spec,))


