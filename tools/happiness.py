def die(msg, code=2):
    print("happiness: ERROR " + msg, file=sys.stderr)
    sys.exit(code)


def path(area):
    return os.path.join(HD, area + ".json")


def load(p):
    with open(p, encoding="utf8") as fh:
        return json.load(fh)


def node(*args):
    if not os.path.isdir(os.path.join(LIFE, "node_modules", "esbuild")):
        subprocess.run(["npm", "install", "--silent", "--no-audit", "--no-fund"], cwd=LIFE, check=False)
