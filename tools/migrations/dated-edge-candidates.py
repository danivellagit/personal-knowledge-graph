#!/usr/bin/env python3
"""READ-ONLY: list "(ex-...)" / "former" prose in people and company nodes that could become a
dated edge (graph.py `edge_dates`, LEGEND.md 2b). Writes a review list, changes no node.

    python3 tools/migrations/dated-edge-candidates.py [--out PATH]

Dated edges come with one rule: no bulk migration. Each candidate is
closed by hand, with evidence, through `python3 tools/graph.py date ...`; unknown dates stay
UNKNOWN, never guessed.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from graph import load_nodes  # noqa: E402

PAT = re.compile(r"\bex-[A-Z][\w&.\- ]{0,30}|\bformer(?:ly)?\b[^.;,)\n]{0,40}|\bpreviously\b[^.;,)\n]{0,40}")
OUT = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else \
    "data/agents/tech-maintainer/reports/dated-edge-candidates.md"


def norm(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main():
    nodes = load_nodes()
    companies = {}
    for s, n in nodes.items():
        if n.type == "companies":
            for v in [s, n.get("name") or ""] + (n.get("aliases") or []):
                if isinstance(v, str) and v.strip():
                    companies[norm(v.strip("\"'"))] = s
    rows = []
    for s, n in sorted(nodes.items()):
        if n.type not in ("people", "companies"):
            continue
        lines = open(n.path, encoding="utf8", errors="ignore").read().split("\n")
        in_fm, key = False, "body"
        for i, line in enumerate(lines, 1):
            if i == 1 and line == "---":
                in_fm = True
                continue
            if in_fm and line == "---":
                in_fm, key = False, "body"
                continue
            if in_fm:
                m = re.match(r"^([A-Za-z_][\w\-]*):", line)
                if m:
                    key = m.group(1)
            for m in PAT.finditer(line):
                txt = m.group(0).strip()
                cand = re.match(r"ex-([\w&.\-]+(?: [A-Z][\w&.\-]+)?)", txt)
                node = "-"
                if cand:
                    for w in (cand.group(1), cand.group(1).split(" ")[0]):
                        if norm(w) in companies:
                            node = "[[%s]]" % companies[norm(w)]
                            break
                rows.append((n.path, i, key, txt.replace("|", "/"), node,
                             "yes" if node != "-" and node[2:-2] in n.link_list("works_at") else "no"))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8") as f:
        f.write("# Dated-edge candidates (review list)\n\nRelated: [[_me]]\n\n")
        f.write("Generated by `tools/migrations/dated-edge-candidates.py` (read-only). Prose that\n"
                "names a past job or relation. Nothing was migrated: the rule is no bulk migration.\n"
                "To close one, with evidence: `python3 tools/graph.py date <slug> works_at <company> --until\n"
                "<YYYY[-MM]|UNKNOWN>` (the edge must exist; create the company node first if it is missing).\n"
                "`node` = a company node matching the name, `edge` = whether the person already has that\n"
                "`works_at` edge. Many matches are not jobs (\"former partner\", \"ex-colleague\"): review each.\n\n")
        f.write("%d matches in %d files.\n\n" % (len(rows), len({r[0] for r in rows})))
        f.write("| file | line | field | text | node | edge |\n| --- | --- | --- | --- | --- | --- |\n")
        for r in rows:
            f.write("| `%s` | %d | %s | %s | %s | %s |\n" % (r[0], r[1], r[2], r[3], r[4], r[5]))
    print("%s: %d matches in %d files" % (OUT, len(rows), len({r[0] for r in rows})))


if __name__ == "__main__":
    main()
